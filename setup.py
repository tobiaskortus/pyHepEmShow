import os
import sys
import subprocess
import glob
import shutil
import platform
try:
    import tomllib
except ImportError:
    #Fallback to tomli for Python versions <3.11
    import tomli as tomllib

import sysconfig

from setuptools import setup, Extension, find_packages
from setuptools.command.build_ext import build_ext as _BuildExt

ROOT = os.path.dirname(os.path.abspath(__file__))
MODULE_NAME = "_core"

# AD modes passed to configure.sh; "backward" is exposed as "reverse" in Python
MODES = ["forward", "forward_ad", "backward"]

def _subpackage(ad_mode):
    return "reverse" if ad_mode == "backward" else ad_mode

with open(os.path.join(ROOT, "pyproject.toml"), "rb") as _f:
    BUILD_TYPE = tomllib.load(_f)["tool"]["pyhepemshow"]["build_type"]


def _build_dir(ad_mode):
    return os.path.join(ROOT, "hepemshow", f"build_{ad_mode}")


def _g4hepem_install_dir(ad_mode):
    return os.path.join(ROOT, "externals", "g4hepem", f"install_{ad_mode}")


def _so_files(ad_mode):
    ext_suffix = sysconfig.get_config_var("EXT_SUFFIX")
    return glob.glob(os.path.join(_build_dir(ad_mode), f"{MODULE_NAME}*{ext_suffix}"))


def _g4hepem_libs(ad_mode):
    lib_dir = os.path.join(_g4hepem_install_dir(ad_mode), "lib")
    if not os.path.isdir(lib_dir):
        lib_dir = os.path.join(_g4hepem_install_dir(ad_mode), "lib64")
    return (
        glob.glob(os.path.join(lib_dir, "libg4HepEm*.dylib"))
        + glob.glob(os.path.join(lib_dir, "libg4HepEm*.so*"))
    )


def _patch_dylib_names(ad_mode, pkg_dir):
    """Rename bundled shared libs with a mode suffix so the dynamic linker treats
    the three mode variants as distinct libraries.  Without this, all three share
    the same install-name / SONAME and the linker serves the first-loaded copy to
    every subsequent extension, producing wrong-type crashes.

    macOS: uses install_name_tool (-id / -change)
    Linux: uses patchelf (--set-soname / --replace-needed)

    Generated by Copilot.
    """
    system = platform.system()
    ext_suffix = sysconfig.get_config_var("EXT_SUFFIX")

    if system == "Darwin":
        lib_pattern, lib_suffix = "libg4HepEm*.dylib", ".dylib"
    elif system == "Linux":
        lib_pattern, lib_suffix = "libg4HepEm*.so*", ".so"
    else:
        return

    libs = glob.glob(os.path.join(pkg_dir, lib_pattern))
    # Build rename map: strip any existing mode suffix then append the current one
    rename_map = {}
    for lib in libs:
        base = os.path.basename(lib)
        # Determine stem up to the first ".so" / ".dylib"
        dot = base.index(lib_suffix)
        stem = base[:dot]
        new_base = f"{stem}_{ad_mode}{base[dot:]}"
        if base != new_base:
            rename_map[base] = new_base

    if not rename_map:
        return

    for old_base, new_base in rename_map.items():
        new_path = os.path.join(pkg_dir, new_base)
        shutil.move(os.path.join(pkg_dir, old_base), new_path)
        if system == "Darwin":
            subprocess.run(["install_name_tool", "-id", f"@rpath/{new_base}", new_path], check=True)
        else:
            subprocess.run(["patchelf", "--set-soname", new_base, new_path], check=True)

    all_binaries = (
        [os.path.join(pkg_dir, nb) for nb in rename_map.values()]
        + glob.glob(os.path.join(pkg_dir, f"*{ext_suffix}"))
    )
    for binary in all_binaries:
        for old_base, new_base in rename_map.items():
            if system == "Darwin":
                subprocess.run(
                    ["install_name_tool", "-change", f"@rpath/{old_base}", f"@rpath/{new_base}", binary],
                    check=False,
                )
            else:
                subprocess.run(
                    ["patchelf", "--replace-needed", old_base, new_base, binary],
                    check=False,
                )


def _init_submodules():
    if not os.path.exists(os.path.join(ROOT, ".git")):
        return
    submodule_dirs = [
        os.path.join(ROOT, "externals", "g4hepem"),
        os.path.join(ROOT, "externals", "CoDiPack"),
    ]
    if any(not os.path.isdir(d) or not os.listdir(d) for d in submodule_dirs):
        subprocess.run(
            ["git", "submodule", "update", "--init", "--recursive"],
            check=True, cwd=ROOT,
        )


def _build_mode(ad_mode):
    _init_submodules()
    subprocess.run(
        ["bash", os.path.join(ROOT, "externals", "configure.sh"),
         ad_mode, "", sys.executable, BUILD_TYPE, ad_mode, MODULE_NAME],
        check=True, cwd=ROOT,
    )
    so_files = _so_files(ad_mode)
    if not so_files:
        raise RuntimeError(f"No extension artifacts found for mode '{ad_mode}' in {_build_dir(ad_mode)}")
    return so_files


class CMakeBuildExt(_BuildExt):
    def run(self):
        src_json = os.path.join(ROOT, "hepemshow", "data", "hepem_data.json")

        # Copy to source tree (editable installs)
        dst_dir = os.path.join(ROOT, "pyhepemshow", "data")
        os.makedirs(dst_dir, exist_ok=True)
        shutil.copy2(src_json, os.path.join(dst_dir, "hepem_data.json"))

        # Copy to build_lib (regular/pip installs)
        build_lib_data_dir = os.path.join(self.build_lib, "pyhepemshow", "data")
        os.makedirs(build_lib_data_dir, exist_ok=True)
        shutil.copy2(src_json, os.path.join(build_lib_data_dir, "hepem_data.json"))

        for ad_mode in MODES:
            so_files = _build_mode(ad_mode)
            libs = _g4hepem_libs(ad_mode)
            subpackage = _subpackage(ad_mode)

            for dest in [
                os.path.join(ROOT, "pyhepemshow", subpackage),       # editable installs
                os.path.join(self.build_lib, "pyhepemshow", subpackage),  # regular installs
            ]:
                os.makedirs(dest, exist_ok=True)
                for stale in (
                    glob.glob(os.path.join(dest, "*.dylib"))
                    + glob.glob(os.path.join(dest, "*.so"))
                    + glob.glob(os.path.join(dest, "*.so.*"))
                ):
                    os.remove(stale)
                for f in so_files + libs:
                    shutil.copy2(f, dest)
                _patch_dylib_names(ad_mode, dest)


setup(
    cmdclass={"build_ext": CMakeBuildExt},
    ext_modules=[
        Extension("pyhepemshow.forward._core",     sources=[]),
        Extension("pyhepemshow.forward_ad._core",  sources=[]),
        Extension("pyhepemshow.reverse._core",     sources=[]),
    ],
    packages=find_packages(include=["pyhepemshow", "pyhepemshow.*"]),
    package_data={
        "pyhepemshow":            ["data/hepem_data.json"],
        "pyhepemshow.forward":    ["*.dylib", "*.so", "*.so.*"],
        "pyhepemshow.forward_ad": ["*.dylib", "*.so", "*.so.*"],
        "pyhepemshow.reverse":    ["*.dylib", "*.so", "*.so.*"],
    },
    include_package_data=True,
)
